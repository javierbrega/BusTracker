export const getLocalizedServiceDescription = (description, language) => {
  if (!description || language === 'es') return description

  return description
    .replace(/lunes a viernes/gi, 'Monday to Friday')
    .replace(/sábados/gi, 'Saturdays')
    .replace(/sábado/gi, 'Saturday')
    .replace(/domingos/gi, 'Sundays')
    .replace(/domingo/gi, 'Sunday')
    .replace(/feriados/gi, 'holidays')
    .replace(/feriado/gi, 'holiday')
    .replace(/días de servicio/gi, 'service days')
    .replace(/día de servicio/gi, 'service day')
    .replace(/\by\b/gi, 'and')
}
